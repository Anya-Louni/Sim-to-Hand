"""How much of each test set every VLM has judged, and how many calls would finish it. No API calls.

  python scripts/coverage_report.py

Reads results/<split>/metrics.json (run evaluate first) and data/<split>/vlm/*.jsonl.
Writes results/coverage.md. The policy (evaluate.policy): under 50% coverage goes to the appendix table;
a judge giving the same answer on 90% or more of its answers is flagged as degenerate.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from vcf.evaluate import DEGENERATE, MIN_COVERAGE, policy  # noqa: E402
from vcf.stats import half_up  # noqa: E402


def main():
    md = (f"VLM coverage per test set. Policy: under {int(MIN_COVERAGE * 100)}% coverage goes to the leaderboard appendix; "
          f"one answer on {int(DEGENERATE * 100)}% or more of its answers is flagged as degenerate. "
          "Calls to finish = samples not yet judged in that mode (one call each). Generated by scripts/coverage_report.py.\n")
    for split in ("small", "large"):
        r = json.loads((ROOT / "results" / split / "metrics.json").read_text())
        n = r["n_test"]
        md += f"\n### {split} ({n} samples)\n\n| Judge | Judged | Coverage | Table | Degenerate | Calls to finish |\n|---|---|---|---|---|---|\n"
        for name, j in sorted(r["judges"].items()):
            if j["kind"] != "vlm":
                continue
            p = policy(j, n)
            k = int(j["coverage"].split("/")[0])
            md += f"| {name} | {k}/{n} | {half_up(p['coverage'], 0, 100)}% | {'main' if p['main'] else 'appendix'} | {'yes' if p['degenerate'] else 'no'} | {n - k} |\n"
    (ROOT / "results" / "coverage.md").write_text(md, encoding="utf-8", newline="\n")
    print(md)


if __name__ == "__main__":
    main()
