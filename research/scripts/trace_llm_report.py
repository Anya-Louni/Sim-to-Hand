"""B2 report: text LLMs reading touch traces, against the sensor classifier and the camera VLM on the same samples.

  python scripts/trace_llm_report.py

Reads data/small/trace_llm/*.jsonl and results/small/predictions.csv. Writes results/trace_llm.md and .json.
No API calls.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from vcf.evaluate import metrics  # noqa: E402
from vcf.stats import half_up, mcnemar, pair_bootstrap  # noqa: E402

REFS = ["sensor_logreg", "gemini/gemini-3.1-flash-lite (single)"]


def main():
    pred = {r["id"]: r for r in csv.DictReader(open(ROOT / "results/small/predictions.csv", encoding="utf-8"))}
    out, md = {}, ("Can a text LLM read a touch trace? Each small-set sample's cheap-sensor trace (same noise as the "
                   "evaluation, printed at 10 Hz) is given to a text-only model with the task description. One-shot adds "
                   "one labelled success/failure pair of the same task from the training seeds. McNemar compares with "
                   "the sensor classifier and the camera VLM on the samples the LLM answered. Generated by "
                   "scripts/trace_llm_report.py.\n\n"
                   "| Reader | Answered | Balanced acc. | False-success | vs sensor_logreg (only LLM / only ref right, p) | vs Flash-Lite camera (only LLM / only ref right, p) |\n|---|---|---|---|---|---|\n")
    for f in sorted((ROOT / "data/small/trace_llm").glob("*.jsonl")):
        rows = [json.loads(l) for l in open(f)]
        rows = [r for r in rows if r["id"] in pred]
        y = np.array([r["label"] for r in rows])
        p = np.array([-1 if r["success"] is None else int(r["success"]) for r in rows])
        pairs = np.array([pred[r["id"]]["pair"] for r in rows])
        m, ci = metrics(y, p), pair_bootstrap(y, p, pairs)
        tests = {}
        for ref in REFS:
            keep = np.array([pred[r["id"]][ref] not in ("", "-2") for r in rows]) & (p != -1)
            q = np.array([int(pred[r["id"]][ref]) if keep[k] else 0 for k, r in enumerate(rows)])
            tests[ref] = mcnemar((p == y)[keep], (q == y)[keep])
        name = f"{rows[0]['model']} ({rows[0]['shots']}-shot)"
        out[name] = {"n": len(rows), "overall": m, "ci": ci, "mcnemar": tests}
        t = lambda k: f"{tests[k]['only_a_correct']} / {tests[k]['only_b_correct']}, p {'< 0.001' if tests[k]['p'] < 0.001 else half_up(tests[k]['p'], 3)}"  # noqa: E731
        md += (f"| {name} | {len(rows)}/100 | {half_up(m['balanced_accuracy'], 2)} [{half_up(ci['balanced_accuracy'][0], 2)}, {half_up(ci['balanced_accuracy'][1], 2)}] | "
               f"{half_up(m['false_success_rate'], 2)} [{half_up(ci['false_success_rate'][0], 2)}, {half_up(ci['false_success_rate'][1], 2)}] | {t(REFS[0])} | {t(REFS[1])} |\n")
    (ROOT / "results/trace_llm.json").write_text(json.dumps(out, indent=2), newline="\n")
    (ROOT / "results/trace_llm.md").write_text(md, encoding="utf-8", newline="\n")
    print(md)


if __name__ == "__main__":
    main()
