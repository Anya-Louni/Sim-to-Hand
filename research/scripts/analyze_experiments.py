def perceived_summary(md: list[str]):
    """Same tasks and conditions as section 1, but the robot aims at the camera's cube estimates."""
    import sys

    sys.path.insert(0, str(ROOT / "research"))
    from vcf.stats import mcnemar

    pe, pa = read("perceived_trials.csv"), read("perceived_attempts.csv")
    if not pe:
        return
    sim = {(e["decider"], e["failure"], e["id"]): e for e in read("trials.csv")}
    rows = []
    for d, fl in sorted({(e["decider"], e["failure"]) for e in pe}, key=lambda k: (FAILURES.index(k[1]), DECIDERS.index(k[0]))):
        g = [e for e in pe if (e["decider"], e["failure"]) == (d, fl)]
        s = [sim[(d, fl, e["id"])] for e in g]
        mc = mcnemar(np.array([B(e["truth"]) for e in g]), np.array([B(e["truth"]) for e in s]))
        rows.append(dict(
            decider=d, failure=fl, n=len(g),
            perceived_success=sum(B(e["truth"]) for e in g), sim_success=sum(B(e["truth"]) for e in s),
            perceived_false_success=sum(B(e["declared"]) and not B(e["truth"]) for e in g), sim_false_success=sum(B(e["declared"]) and not B(e["truth"]) for e in s),
            perceived_attempts=np.mean([int(e["attempts"]) for e in g]), sim_attempts=np.mean([int(e["attempts"]) for e in s]),
            only_perceived=mc["only_a_correct"], only_sim=mc["only_b_correct"], p=mc["p"],
        ))
    err = np.array([float(a["perceptionMm"]) for a in pa if a["perceptionMm"]])
    worst = np.array([float(a["perceptionMaxMm"]) for a in pa if a["perceptionMaxMm"]])
    missing = sum(int(a["perceptionMissing"] or 0) > 0 for a in pa)
    first = [a for a in pa if a["attempt"] == "0" and a["decider"] == "oracle" and a["perceptionMaxMm"]]
    lo = [a for a in first if float(a["perceptionMaxMm"]) < 5]
    hi = [a for a in first if float(a["perceptionMaxMm"]) >= 5]
    stats = dict(attempts=len(pa), mean_mm=float(err.mean()), median_mm=float(np.median(err)), p90_mm=float(np.percentile(err, 90)),
                 worst_p90_mm=float(np.percentile(worst, 90)), worst_max_mm=float(worst.max()), attempts_with_missing=missing,
                 first_ok_low=sum(B(a["truth"]) for a in lo), first_n_low=len(lo), first_ok_high=sum(B(a["truth"]) for a in hi), first_n_high=len(hi))
    with open(EXP / "summary_perceived.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    (EXP / "summary_perception.json").write_text(json.dumps({k: round(v, 3) if isinstance(v, float) else v for k, v in stats.items()}, indent=2), newline="\n")
    md += [
        "## 3. Perceived state: the robot aims where the camera says the cubes are",
        "",
        "Same tasks and conditions as section 1. Before every attempt the OpenCV detector (research/vcf/detect.py) fits each",
        "cube's pose in the verification image; moves and grasps aim at those estimates. Where the robot places a cube it",
        "assumes the cube is now there. The physics and the scoring still use the true state. McNemar compares true success",
        "on the same task between perceived and true state.",
        "",
        "| Decider | Failure | Episodes | True success, perceived | True success, sim state | False success, perceived | False success, sim state | Avg attempts (perceived / sim) | McNemar (only perceived / only sim, p) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        md.append(f"| {LABEL[r['decider']]} | {FAIL_LABEL[r['failure']]} | {r['n']} | {fmt(r['perceived_success'], r['n'])} | {fmt(r['sim_success'], r['n'])} | "
                  f"{fmt(r['perceived_false_success'], r['n'])} | {fmt(r['sim_false_success'], r['n'])} | {half_up(r['perceived_attempts'], 2)} / {half_up(r['sim_attempts'], 2)} | "
                  f"{r['only_perceived']} / {r['only_sim']}, p {'< 0.001' if r['p'] < 0.001 else half_up(r['p'], 3)} |")
    md += [
        "",
        f"Perception error over {stats['attempts']} looks (sideways distance between estimated and true cube centre, averaged over the cubes in view):",
        f"mean {half_up(stats['mean_mm'], 1)} mm, median {half_up(stats['median_mm'], 1)} mm, 90th percentile {half_up(stats['p90_mm'], 1)} mm. Worst cube per look: 90th percentile",
        f"{half_up(stats['worst_p90_mm'], 1)} mm, largest {half_up(stats['worst_max_mm'], 1)} mm. Looks with a cube not found: {missing}.",
        f"First attempts (simulator decider) with every cube within 5 mm: {fmt(stats['first_ok_low'], stats['first_n_low'])} succeeded;",
        f"with a cube 5 mm or more off: {fmt(stats['first_ok_high'], stats['first_n_high'])}.",
        "",
    ]


