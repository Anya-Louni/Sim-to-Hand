def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float, float]:
    if n == 0:
        return (float("nan"),) * 3
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def fmt(k: int, n: int) -> str:
    if n == 0:
        return "n/a"
    p, lo, hi = wilson(k, n)
    return f"{k}/{n} = {half_up(p, 0, 100)}% [{half_up(lo, 0, 100)}, {half_up(hi, 0, 100)}]"


def read(name: str) -> list[dict]:
    p = DATA / name
    return list(csv.DictReader(open(p, encoding="utf-8"))) if p.exists() else []


B = lambda v: str(v).lower() == "true"  # noqa: E731


# ---------------- Episodes ----------------
def trials_summary(md: list[str]):
    eps = read("trials.csv")
    att = read("attempts.csv")
    if not eps:
        return
    by_ep = defaultdict(list)
    for a in att:
        by_ep[a["key"].rsplit("/", 1)[0]].append(a)
    groups = defaultdict(list)
    for e in eps:
        # A scripted failure only counts where it fired (moving the target needs a cube target).
        if e["failure"] in ("slip", "displace", "knock") and not e["injected"]:
            continue
        groups[(e["decider"], e["failure"])].append(e)

    rows = []
    for f in FAILURES:
        for d in DECIDERS:
            g = groups.get((d, f), [])
            if not g:
                continue
            n = len(g)
            ok = sum(B(e["truth"]) for e in g)
            false_ok = sum(B(e["declared"]) and not B(e["truth"]) for e in g)
            first_fail = [e for e in g if not B(e["firstTruth"])]
            recovered = sum(B(e["truth"]) and B(e["declared"]) for e in first_fail)
            caught = sum(not B(e["firstDeclared"]) for e in first_fail)
            # Time from attempt start until the first failed attempt ended (a failed step or the final check).
            t_detect = [float(a["seconds"]) for e in first_fail if not B(e["firstDeclared"]) for a in by_ep[e["key"]] if a["attempt"] == "0"]
            rows.append(
                dict(
                    failure=f, decider=d, n=n, success=ok, false_success=false_ok, first_failures=len(first_fail), caught=caught, recovered=recovered,
                    mean_attempts=np.mean([int(e["attempts"]) for e in g]), mean_sim_s=np.mean([float(e["simSeconds"]) for e in g]),
                    mean_detect_s=np.mean(t_detect) if t_detect else float("nan"),
                )
            )
    with open(EXP / "summary_trials.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    tasks = len({e["id"] for e in eps})
    md += [
        "## 1. Full episodes: who decides that the task is done",
        "",
        f"{tasks} seeded tasks (stack, tower, sort, zone; generated by `generateTasks(20, 1000)`), scripted planner, up to 3 replans.",
        "Each row is one decision rule. The simulator's own state is the ground truth used for scoring in every row;",
        "only the reference row also uses it to decide. Camera only means the robot also runs without touch or force sensing.",
        "",
        "- **True success**: the goal really holds at the end.",
        "- **False success**: the agent said it was done but the goal does not hold.",
        "- **Caught**: of the episodes whose first attempt really failed, how many the agent noticed.",
        "- **Recovered**: of those, how many ended in a real, declared success after replanning.",
        "- **Time to detect**: simulated seconds from the start of the first attempt until it ended as failed.",
        "",
        "Brackets are 95% Wilson confidence intervals.",
        "",
    ]
    for f in FAILURES:
        sub = [r for r in rows if r["failure"] == f]
        if not sub:
            continue
        md += [f"### {FAIL_LABEL[f]}", "", "| Decider | Episodes | True success | False success | Caught | Recovered | Avg attempts | Time to detect (s) |", "|---|---|---|---|---|---|---|---|"]
        for r in sub:
            md.append(
                f"| {LABEL[r['decider']]} | {r['n']} | {fmt(r['success'], r['n'])} | {fmt(r['false_success'], r['n'])} | {fmt(r['caught'], r['first_failures'])} | "
                f"{fmt(r['recovered'], r['first_failures'])} | {half_up(r['mean_attempts'], 2)} | {'' if math.isnan(r['mean_detect_s']) else f'{half_up(r['mean_detect_s'], 1)}'} |"
            )
        md.append("")

    # Figure: true success and false success by failure type.
    for metric, title, fname in (("success", "True success rate", "trials_success.png"), ("false_success", "False success rate (said done, was not)", "trials_false_success.png")):
        fig, ax = plt.subplots(figsize=(8.4, 3.6))
        x = np.arange(len(FAILURES))
        wbar = 0.2
        for i, d in enumerate(DECIDERS):
            vals, lo, hi = [], [], []
            for f in FAILURES:
                r = next((r for r in rows if r["failure"] == f and r["decider"] == d), None)
                p, l, h = wilson(r[metric], r["n"]) if r else (np.nan,) * 3
                vals.append(p)
                lo.append(p - l)
                hi.append(h - p)
            ax.bar(x + (i - 1.5) * wbar, vals, wbar, yerr=[lo, hi], capsize=2, color=COLOR[d], label=LABEL[d], error_kw={"lw": 0.8})
            for xi, v in zip(x + (i - 1.5) * wbar, vals):
                if v == 0:
                    ax.text(xi, 0.012, "0", ha="center", fontsize=7, color=COLOR[d], fontweight="bold")
        ax.set_xticks(x, [FAIL_LABEL[f] for f in FAILURES])
        ax.set_ylim(0, 1.05)
        ax.set_ylabel(title)
        ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0))
        ax.legend(ncol=4, fontsize=8, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.16))
        fig.tight_layout()
        fig.savefig(FIG / fname)
        plt.close(fig)

    # Figure: recovery and time to detect for the scripted failures.
    fig, axs = plt.subplots(1, 2, figsize=(8.4, 3.2))
    fs = ["slip", "displace", "knock", "chaos"]
    x = np.arange(len(fs))
    for i, d in enumerate(DECIDERS):
        vals, lo, hi, ts = [], [], [], []
        for f in fs:
            r = next((r for r in rows if r["failure"] == f and r["decider"] == d), None)
            p, l, h = wilson(r["recovered"], r["first_failures"]) if r else (np.nan,) * 3
            vals.append(p)
            lo.append(p - l if not np.isnan(p) else 0)
            hi.append(h - p if not np.isnan(p) else 0)
            ts.append(r["mean_detect_s"] if r else np.nan)
        axs[0].bar(x + (i - 1.5) * 0.2, vals, 0.2, yerr=[lo, hi], capsize=2, color=COLOR[d], label=LABEL[d], error_kw={"lw": 0.8})
        axs[1].bar(x + (i - 1.5) * 0.2, ts, 0.2, color=COLOR[d])
    for ax, t in zip(axs, ("Recovered after a real first failure", "Seconds until the first failure is noticed")):
        ax.set_xticks(x, [FAIL_LABEL[f].replace(" ", "\n", 1) for f in fs], fontsize=8)
        ax.set_title(t, fontsize=10)
    axs[0].set_ylim(0, 1.05)
    axs[0].yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0))
    axs[0].legend(fontsize=7, frameon=False)
    fig.tight_layout()
    fig.savefig(FIG / "trials_recovery.png")
    plt.close(fig)


# ---------------- Checkpoints ----------------
def checkpoints_summary(md: list[str]):
    cps = read("checkpoints.csv")
    if not cps:
        return
    cam = {r["id"]: r for r in read("checkpoints_camera.csv")}
    vlms = {}
    for p in sorted(DATA.glob("checkpoints_vlm_*.csv")):
        vlms[p.stem.replace("checkpoints_vlm_", "")] = {r["id"]: r for r in csv.DictReader(open(p, encoding="utf-8"))}

    def verdicts(r):
        v = {"sensors": B(r["sensorContact"])}
        if r["id"] in cam:
            v["camera"] = B(cam[r["id"]]["camera"])
            v["combined"] = v["sensors"] and v["camera"]
        for m, t in vlms.items():
            if r["id"] in t and t[r["id"]]["vlm"] in ("True", "False"):
                v[f"vlm:{m}"] = B(t[r["id"]]["vlm"])
        return v

    hov = [float(r["gapMm"]) for r in cps if r["kind"] == "contact" and not B(r["truth"]) and float(r["gapMm"]) > 1]
    gmin, gmax = min(hov), max(hov)
    rows = []
    for kind in ("contact", "place"):
        sub = [r for r in cps if r["kind"] == kind]
        names = ["camera", "sensors", "combined"] + [f"vlm:{m}" for m in vlms]
        for name in names:
            pairs = [(B(r["truth"]), verdicts(r).get(name)) for r in sub]
            pairs = [(t, p) for t, p in pairs if p is not None]
            if not pairs:
                continue
            pos = [p for t, p in pairs if t]
            neg = [p for t, p in pairs if not t]
            tp, tn = sum(pos), sum(not p for p in neg)
            rows.append(dict(kind=kind, verifier=name, n=len(pairs), n_success=len(pos), n_failure=len(neg), correct=tp + tn, tp=tp, tn=tn, false_success=len(neg) - tn,
                             balanced=(tp / len(pos) + tn / len(neg)) / 2 if pos and neg else float("nan")))
    with open(EXP / "summary_checkpoints.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    md += [
        "## 2. Checkpoints built to be hard for the camera",
        "",
        "Minimal pairs from the agent's own robot and cubes. Half of each set succeeds and half fails, by construction (even seeds succeed).",
        "",
        f"- **Contact**: the robot lowers a held cube onto another and stops either in contact or hovering just above it (measured gaps {half_up(gmin, 1)} to {half_up(gmax, 1)} mm). "
        "The image is taken at that moment, gripper in view. Ground truth is the simulated gap (contact means under 0.5 mm).",
        "- **Placement**: the robot releases the cube on top of another, either centered (0 to 10 mm off) or 28 to 36 mm off along a face, "
        "so it tips off. The image is taken after the arm moves away. Ground truth is the simulator's `on` check.",
        "",
        "Sensors: the agent's rule (wrist force rises more than 2 N while lowering). Camera: OpenCV detector (`research/vcf/detect.py`), image only. "
        "Combined: success only if both say success.",
        "",
        "| Checkpoint | Verifier | Pairs | Accuracy | Catches failures | Passes successes | False success |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        name = LABEL.get(r["verifier"], r["verifier"].replace("vlm:", "VLM "))
        md.append(f"| {r['kind']} | {name} | {r['n']} | {fmt(r['correct'], r['n'])} | {fmt(r['tn'], r['n_failure'])} | {fmt(r['tp'], r['n_success'])} | {fmt(r['false_success'], r['n_failure'])} |")
    md.append("")

    fig, axs = plt.subplots(1, 2, figsize=(8.4, 3.2), sharey=True)
    for ax, kind, title in zip(axs, ("contact", "place"), (f"Contact: touching or hovering {half_up(gmin, 1)} to {half_up(gmax, 1)} mm", "Placement: stays on top or tips off")):
        sub = [r for r in rows if r["kind"] == kind]
        for i, r in enumerate(sub):
            p, lo, hi = wilson(r["correct"], r["n"])
            key = "vlm" if r["verifier"].startswith("vlm") else r["verifier"]
            ax.bar(i, p, 0.65, yerr=[[p - lo], [hi - p]], capsize=3, color=COLOR[key])
            ax.text(i, 0.03, f"n={r['n']}", ha="center", fontsize=7, color="white")
        ax.set_xticks(range(len(sub)), [LABEL.get(r["verifier"], "VLM").replace(" + ", "\n+ ").replace(" only", "\nonly") for r in sub], fontsize=8)
        ax.axhline(0.5, color="#888", lw=0.8, ls="--")
        ax.set_title(title, fontsize=10)
    axs[0].set_ylabel("Accuracy (half fail, half succeed)")
    axs[0].set_ylim(0, 1.05)
    axs[0].yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0))
    fig.tight_layout()
    fig.savefig(FIG / "checkpoints_accuracy.png")
    plt.close(fig)

    # Contact: how often each check says "touching", by true gap.
    sub = [r for r in cps if r["kind"] == "contact" and r["gapMm"]]
    if sub:
        gaps = np.array([float(r["gapMm"]) for r in sub])
        bins = [-2, 0.5, 2.0, 2.5, 3.0, 3.5, 4.5, 6]
        fig, ax = plt.subplots(figsize=(5.6, 3.2))
        mids = [(bins[i] + bins[i + 1]) / 2 if i else 0 for i in range(len(bins) - 1)]
        labels = ["touching"] + [f"{bins[i]:g}-{bins[i + 1]:g}" for i in range(1, len(bins) - 1)]
        for name in ("camera", "sensors"):
            ys = []
            for i in range(len(bins) - 1):
                m = [verdicts(r).get(name) for r, gp in zip(sub, gaps) if bins[i] <= gp < bins[i + 1]]
                m = [v for v in m if v is not None]
                ys.append(np.mean(m) if m else np.nan)
            ax.plot(range(len(ys)), ys, "o-", color=COLOR[name], label=LABEL[name])
        ax.set_xticks(range(len(labels)), labels, fontsize=8)
        ax.set_xlabel("True gap (mm)")
        ax.set_ylabel('Says "touching"')
        ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0))
        ax.set_ylim(-0.03, 1.03)
        ax.legend(frameon=False, fontsize=8)
        fig.tight_layout()
        fig.savefig(FIG / "checkpoints_contact_gap.png")
        plt.close(fig)


