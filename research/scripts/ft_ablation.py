"""A7: does a 6-axis wrist force/torque sensor beat the single-axis wrist force reading?

  python scripts/ft_ablation.py

Same switches, effort channel, classifiers, training seeds and noise draws for both sets; only the wrist sensor
changes. Writes results/ft_ablation.json, results/ft_ablation.md and results/ft_ablation.png. No API calls.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from vcf.evaluate import TASKS, by_task, load, metrics, sensor_models  # noqa: E402
from vcf.sensors import feature_matrix  # noqa: E402
from vcf.stats import half_up, mcnemar, pair_bootstrap  # noqa: E402

SETS = ["single", "ft6"]
TRAIN = [ROOT / "data/sensor_train_s1", ROOT / "data/sensor_train_s2"]
SWEEP = [0, 0.5, 1, 2, 4, 8, 16, 32]


def ft_traces(dirs):
    out = {}
    for d in dirs:
        out.update(dict(np.load(d / "sensors_ft.npz")))
    return out


def evaluate(split: str) -> dict:
    test, tr = load([ROOT / "data" / split])
    train, trtr = load(TRAIN)
    fte, ftr = ft_traces([ROOT / "data" / split]), ft_traces(TRAIN)
    ids, tids = [s["id"] for s in test], [s["id"] for s in train]
    y, ytr = np.array([s["label"] for s in test]), np.array([s["label"] for s in train])
    pairs = np.array([s["pair"] for s in test])
    res: dict = {"n_test": len(test), "sets": {}}
    correct = {}
    for ss in SETS:
        X = lambda traces, ft, idl, st, seed: feature_matrix(traces, idl, st, seed, sensor_set=ss, ft=ft)  # noqa: E731
        Xtr, Xte = X(trtr, ftr, tids, 1.0, 1), X(tr, fte, ids, 1.0, 2)
        r: dict = {"judges": {}, "loto": {}, "sweep": []}
        for name, clf in sensor_models().items():
            p = clf.fit(Xtr, ytr).predict_proba(Xte)[:, 1]
            pred = (p >= 0.5).astype(int)
            m = metrics(y, pred, p)
            m.pop("reliability", None)
            r["judges"][name] = {"overall": m, "ci": pair_bootstrap(y, pred, pairs), "by_task": by_task(test, y, pred)}
            correct[(ss, name)] = pred == y
        for t in TASKS:
            trm, tem = np.array([s["task"] != t for s in train]), np.array([s["task"] == t for s in test])
            pl = (sensor_models()["sensor_logreg"].fit(Xtr[trm], ytr[trm]).predict_proba(Xte[tem])[:, 1] >= 0.5).astype(int)
            r["loto"][t] = {**metrics(y[tem], pl), "ci": pair_bootstrap(y[tem], pl, pairs[tem])}
        for st in SWEEP:
            pred = (sensor_models()["sensor_logreg"].fit(X(trtr, ftr, tids, st, 1), ytr).predict_proba(X(tr, fte, ids, st, 2))[:, 1] >= 0.5).astype(int)
            mm = metrics(y, pred)
            r["sweep"].append({"strength": st, "balanced_accuracy": mm["balanced_accuracy"], "false_success_rate": mm["false_success_rate"], "ci": pair_bootstrap(y, pred, pairs)})
        res["sets"][ss] = r
    res["mcnemar_ft6_vs_single"] = {name: mcnemar(correct[("ft6", name)], correct[("single", name)]) for name in sensor_models()}
    return res


def n(x):
    return half_up(x, 2)


def ci(c):
    return f"[{half_up(c[0], 2)}, {half_up(c[1], 2)}]"


def p_txt(p):
    return "< 0.001" if p < 0.001 else half_up(p, 3)


def write_md(all_: dict) -> str:
    md = ("Wrist sensor ablation (A7). Same switches, effort channel, training data and noise draws; only the wrist "
          "sensor changes. single = one force axis along the tool; ft6 = 6-axis force/torque with task-agnostic "
          "features (contact onset, peak change, direction vs approach, stability after onset, torque). "
          "Balanced accuracy with 95% pair-bootstrap intervals. Generated by scripts/ft_ablation.py.\n")
    for split, r in all_.items():
        md += f"\n### Test set {split} ({r['n_test']} samples)\n\n| Classifier | single | ft6 | McNemar (ft6 better / single better, p) |\n|---|---|---|---|\n"
        for name in r["sets"]["single"]["judges"]:
            a, b = r["sets"]["single"]["judges"][name], r["sets"]["ft6"]["judges"][name]
            mc = r["mcnemar_ft6_vs_single"][name]
            md += (f"| {name} | {n(a['overall']['balanced_accuracy'])} {ci(a['ci']['balanced_accuracy'])} | "
                   f"{n(b['overall']['balanced_accuracy'])} {ci(b['ci']['balanced_accuracy'])} | {mc['only_a_correct']} / {mc['only_b_correct']}, p {p_txt(mc['p'])} |\n")
        md += "\nPer task, logistic regression (balanced accuracy):\n\n| Task | single | ft6 | held out: single | held out: ft6 |\n|---|---|---|---|---|\n"
        for t in TASKS:
            s1, s2 = r["sets"]["single"], r["sets"]["ft6"]
            md += (f"| {t} | {n(s1['judges']['sensor_logreg']['by_task'][t]['balanced_accuracy'])} | {n(s2['judges']['sensor_logreg']['by_task'][t]['balanced_accuracy'])} | "
                   f"{n(s1['loto'][t]['balanced_accuracy'])} {ci(s1['loto'][t]['ci']['balanced_accuracy'])} | {n(s2['loto'][t]['balanced_accuracy'])} {ci(s2['loto'][t]['ci']['balanced_accuracy'])} |\n")
        md += "\nNoise sweep, logistic regression (balanced accuracy):\n\n| Strength | single | ft6 |\n|---|---|---|\n"
        for a, b in zip(r["sets"]["single"]["sweep"], r["sets"]["ft6"]["sweep"]):
            md += f"| {a['strength']} | {n(a['balanced_accuracy'])} {ci(a['ci']['balanced_accuracy'])} | {n(b['balanced_accuracy'])} {ci(b['ci']['balanced_accuracy'])} |\n"
    return md


def plot(all_: dict, out: Path):
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
    for ax, (split, r) in zip(axes, all_.items()):
        for ss, style in (("single", "o-"), ("ft6", "s--")):
            sw = r["sets"][ss]["sweep"]
            x = [max(s["strength"], 0.25) for s in sw]
            ax.semilogx(x, [s["balanced_accuracy"] for s in sw], style, label=ss)
            ax.fill_between(x, [s["ci"]["balanced_accuracy"][0] for s in sw], [s["ci"]["balanced_accuracy"][1] for s in sw], alpha=0.15)
        ax.axhline(0.5, color="gray", lw=0.8, ls=":")
        ax.set_title(f"{split} test set")
        ax.set_xlabel("sensor noise strength (leftmost point is 0)")
        ax.set_ylim(0.4, 1.02)
    axes[0].set_ylabel("balanced accuracy")
    axes[0].legend()
    fig.tight_layout()
    fig.savefig(out, dpi=150)


def main():
    all_ = {split: evaluate(split) for split in ("small", "large")}
    out = ROOT / "results"
    (out / "ft_ablation.json").write_text(json.dumps(all_, indent=2), newline="\n")
    md = write_md(all_)
    (out / "ft_ablation.md").write_text(md, encoding="utf-8", newline="\n")
    plot(all_, out / "ft_ablation.png")
    print(md)


if __name__ == "__main__":
    main()
